/// Represents a supported currency with its ISO-4217 code, name, symbol, and primary country/territory.
class CurrencyInfo {
  const CurrencyInfo({
    required this.code,
    required this.name,
    required this.symbol,
    required this.country,
    this.flag = '',
  });

  /// 3-letter ISO 4217 currency code (e.g. "PKR", "USD", "EUR").
  final String code;

  /// Human-readable currency name (e.g. "Pakistani Rupee", "US Dollar").
  final String name;

  /// Display symbol or prefix (e.g. "Rs ", "$", "€").
  final String symbol;

  /// Primary country or issuing jurisdiction recognized by Pakistan.
  final String country;

  /// Optional country flag emoji.
  final String flag;

  /// Display label formatted for selectors and lists.
  String get displayLabel => flag.isNotEmpty
      ? '$flag $code - $name ($symbol)'
      : '$code - $name ($symbol)';

  @override
  bool operator ==(Object other) =>
      identical(this, other) ||
      other is CurrencyInfo &&
          runtimeType == other.runtimeType &&
          code == other.code;

  @override
  int get hashCode => code.hashCode;

  @override
  String toString() => '$code ($name)';
}

