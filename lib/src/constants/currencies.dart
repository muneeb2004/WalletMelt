/// Returns the CurrencyInfo for a given currency code, or null if unsupported.
CurrencyInfo? findCurrency(String? code) {
  if (code == null || code.isEmpty) return null;
  return _currencyCodeMap[code.toUpperCase()];
}

/// Checks whether a currency code belongs to a recognized country supported by WalletMelt.
bool isCurrencySupported(String? code) {
  if (code == null || code.isEmpty) return false;
  return _currencyCodeMap.containsKey(code.toUpperCase());
}

/// Returns the display symbol for a given currency code.
String currencySymbolFor(String currency) {
  final info = findCurrency(currency);
  if (info != null) {
    return info.symbol;
  }
  return '$currency ';
}
